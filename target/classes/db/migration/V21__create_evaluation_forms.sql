CREATE TABLE IF NOT EXISTS evaluation_forms (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    intern_id BIGINT NOT NULL,
    supervisor_id BIGINT NOT NULL,
    form_type VARCHAR(32) NOT NULL,
    week_number INT NOT NULL,
    submission_date DATETIME(6) NULL,
    status VARCHAR(32) NOT NULL,
    attendance_rating DECIMAL(4,2) NULL,
    task_completion_rating DECIMAL(4,2) NULL,
    work_quality_rating DECIMAL(4,2) NULL,
    technical_skills_rating DECIMAL(4,2) NULL,
    conduct_engagement_rating DECIMAL(4,2) NULL,
    attendance_comment TEXT NULL,
    task_completion_comment TEXT NULL,
    work_quality_comment TEXT NULL,
    technical_skills_comment TEXT NULL,
    conduct_comment TEXT NULL,
    general_comment TEXT NULL,
    ai_computed_score DECIMAL(6,2) NULL,
    ai_grade VARCHAR(32) NULL,
    ai_prediction VARCHAR(32) NULL,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    KEY idx_eval_forms_intern (intern_id),
    KEY idx_eval_forms_supervisor (supervisor_id),
    KEY idx_eval_forms_type (form_type),
    KEY idx_eval_forms_status (status),
    CONSTRAINT fk_eval_forms_intern FOREIGN KEY (intern_id) REFERENCES interns(id),
    CONSTRAINT fk_eval_forms_supervisor FOREIGN KEY (supervisor_id) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
